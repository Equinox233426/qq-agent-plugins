// 省 token：合并 send_message 与 finish（可开关的提示词补丁）
//
// ── 为什么要这个 ────────────────────────────────────────────────────────────
// 实测数据（2026-09-27）：
//   · 今日 prompt 28.8M / 输出 42.5 万 / 缓存命中 94.1% / 763 次 run / 约 3.95 元
//   · 成本构成：输出 43%、未命中输入 43%、**静态提示词只占 5%**（已 94% 缓存，省它没用）
//   · 输出里 **74% 是模型思考**（31.5 万 / 42.5 万）
//   · 平均轮数 2.47；其中 2 轮的 run 有 383 个
//
// 而那 383 个 2 轮 run 的结构是固定的：
//   第 1 轮  send_message   → 发言发出
//   第 2 轮  finish         → 只为了说一句"我收尾了"
// 也就是说：**每发一次言要打两次模型调用**，第 2 轮的全部产出就是那句收尾理由。
//
// 机制上可以合并：orchestrator 的循环是
//   `for (let round = 0; round < maxRounds && !finish; round++)`
// 且**一轮响应里的多个工具调用是顺序执行的** —— 所以只要模型在**同一次响应**里
// 同时调 send_message 和 finish，就只花 1 轮。
//
// 省多少：省一轮 ≈ 0.223 分 → 383 个 2 轮 run 约省 0.85 元/天，
// 按 763 run 推算约 1.7 元/天（约四成）。
//
// ── 代价（要清楚）────────────────────────────────────────────────────────────
// `finish` 的 `summary` 参数是"模型给自己的收尾理由"，只显示在管理端会话卡片上，
// 不发到群里（你截图里那个「回怼 zozo 一句，等后续」就是它）。
// 不调 finish 之后，那个字段会是空的 —— 拿"能看到它为什么这么做"换"省四成钱"。
//
// 另外：活跃期（chatActive）靠 finish 带回 activeTopic 才能开启。实测这一点**无影响**：
// 766 个会话、759 次 finish 调用里，activeTopic **填了 0 次**，该功能从未激活过。
//
// ── 怎么开关 / 怎么回退 ──────────────────────────────────────────────────────
//   开关：QQ Agent →「插件」页 → 找到「省token·合并收尾」→ 启用/禁用
//   回退：禁用或删掉 plugins/finish-merge/ 目录，行为立刻恢复原样（不碰你的配置）
//   ⚠️ promptSections 只在 Skill **激活**时才会被收集（manager.getPromptSections
//      里先判 isActive），所以"禁用"是真的不生效，不会残留。

let log = () => {};

const NOTE = [
  '【收尾：打完字就直接结束，不用再单独调 finish】',
  '- 想说话就调 send_message；说完这一轮就结束，**不要再单独调一次 finish**。',
  '- 你可以在同一次响应里同时调 send_message 和 finish（两个一起调也只算一轮），',
  '  但不要"先发消息、等结果、再专门调一次 finish"——那会白白多打一次模型调用。',
  '- 系统在没有工具调用的那一轮会自然结束，不需要你显式收尾。',
  '- 决定不说话时（看完决定不接），直接结束就行，也不必调 finish。'
].join('\n');

export function setup(api) {
  log = api.log;
  log('省token·合并收尾已生效：提示模型在一次响应里完成 send_message + finish');
}

/**
 * 动态提示词片段：只在插件激活时被收集（manager.getPromptSections 会先判 isActive）。
 * 返回空数组即"不加任何东西"，便于将来做配置开关（当前不需要）。
 */
export function promptSections() {
  return [{
    id: 'finish-merge-note',
    title: '收尾省一轮',
    // 优先级给高一点：要压过工具说明里那句"（或调用 finish）"
    priority: 60,
    content: NOTE
  }];
}

/** 可用性：无外部依赖。 */
export function available() {
  return { ok: true };
}
